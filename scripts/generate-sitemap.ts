/**
 * Regenerate public/sitemap.xml from the real route table and stock universe.
 *
 * The committed sitemap had drifted badly from the app:
 *   - 19 of 282 stocks listed (93% of the indexable inventory missing)
 *   - 15 of 16 /sectors/* URLs were Indian slugs (pharma, fmcg, auto, banking,
 *     it, metal, cement, realestate, …) with no matching PSE sector — all soft
 *     404s. The real registry has exactly six.
 *   - 8 /scanner/* "preset" URLs, of which only one is even a recognised legacy
 *     alias. Unknown presets silently fall back to `gainers`, so those URLs all
 *     served identical content — duplicate content, from our own sitemap.
 *   - /methodology had no route at all.
 *   - No <lastmod> on any entry.
 *
 * Everything emitted here is cross-checked against a real source: symbols from
 * data/stock-universe.json, sector slugs from SectorContentService, scanner
 * modes from ScannerPage's VALID_MODES, and static paths from routes.tsx.
 * Auth-gated routes (watchlist, portfolio, settings, alerts, billing, ops) are
 * deliberately excluded — they are noindex-appropriate and never public.
 *
 *   npx tsx scripts/generate-sitemap.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const OUTPUT = path.join(root, "public", "sitemap.xml");

/**
 * Canonical origin. Mirrors src/config/domain.ts's production default, but read
 * from the environment rather than imported — domain.ts is Vite-only code
 * (import.meta.env) and throws under plain Node.
 */
const ORIGIN = (process.env.VITE_APP_ORIGIN ?? "https://stockstory-india.com").replace(/\/+$/, "");

interface SitemapEntry {
  path: string;
  changefreq: "daily" | "weekly" | "monthly";
  priority: string;
}

/** Public, indexable static routes — each verified against src/app/routes.tsx. */
const STATIC_ROUTES: SitemapEntry[] = [
  { path: "/", changefreq: "daily", priority: "1.0" },
  { path: "/scanner", changefreq: "daily", priority: "0.9" },
  { path: "/sectors", changefreq: "weekly", priority: "0.8" },
  { path: "/compare", changefreq: "weekly", priority: "0.7" },
  { path: "/pricing", changefreq: "monthly", priority: "0.6" },
  { path: "/trust", changefreq: "monthly", priority: "0.5" },
  { path: "/about", changefreq: "monthly", priority: "0.5" },
];

/** Real sort modes from ScannerPage's VALID_MODES. */
const SCANNER_MODES = ["gainers", "losers", "active", "all", "breakout"];

/** Real PSE sector slugs from SectorContentService. */
const SECTOR_SLUGS = [
  "financials",
  "industrial",
  "holding-firms",
  "property",
  "services",
  "mining-oil",
];

function loadUniverse(): { symbols: string[]; generatedAt: string } {
  const raw = JSON.parse(readFileSync(path.join(root, "data", "stock-universe.json"), "utf-8"));
  const symbols = (raw.entries ?? [])
    .map((e: { symbol: string }) => e.symbol)
    .filter(Boolean)
    .sort();
  return { symbols, generatedAt: raw.generatedAt ?? new Date().toISOString() };
}

function urlBlock(loc: string, changefreq: string, priority: string, lastmod: string): string {
  return [
    "  <url>",
    `    <loc>${loc}</loc>`,
    `    <lastmod>${lastmod}</lastmod>`,
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
    "  </url>",
  ].join("\n");
}

function main() {
  const { symbols, generatedAt } = loadUniverse();
  if (symbols.length === 0) {
    throw new Error("stock-universe.json has no entries — run scripts/generate-stock-universe.ts first.");
  }

  // Date-only, per the sitemap spec's W3C date format.
  const lastmod = generatedAt.slice(0, 10);
  const blocks: string[] = [];

  for (const route of STATIC_ROUTES) {
    blocks.push(urlBlock(`${ORIGIN}${route.path}`, route.changefreq, route.priority, lastmod));
  }
  for (const mode of SCANNER_MODES) {
    blocks.push(urlBlock(`${ORIGIN}/scanner/${mode}`, "daily", "0.7", lastmod));
  }
  for (const slug of SECTOR_SLUGS) {
    blocks.push(urlBlock(`${ORIGIN}/sectors/${slug}`, "weekly", "0.7", lastmod));
  }
  for (const symbol of symbols) {
    blocks.push(urlBlock(`${ORIGIN}/stock/${symbol}`, "daily", "0.8", lastmod));
  }

  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by scripts/generate-sitemap.ts — do not edit by hand. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...blocks,
    "</urlset>",
    "",
  ].join("\n");

  writeFileSync(OUTPUT, xml);

  console.log(`Wrote ${blocks.length} URLs to ${OUTPUT}`);
  console.log(`  origin        : ${ORIGIN}`);
  console.log(`  stock pages   : ${symbols.length}`);
  console.log(`  scanner modes : ${SCANNER_MODES.length}`);
  console.log(`  sectors       : ${SECTOR_SLUGS.length}`);
  console.log(`  static        : ${STATIC_ROUTES.length}`);
  console.log(`  lastmod       : ${lastmod}`);
}

main();
